GEMINI_API_KEY = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")  # set in .env / environment - never hard-code

# if not os.getenv("GOOGLE_API_KEY"):
#     raise ValueError("Please set the GOOGLE_API_KEY environment variable.")

# genai.configure(api_key=os.getenv("GOOGLE_API_KEY"))
client = genai.Client(api_key=GEMINI_API_KEY)

# ------------- System prompts (from your session doc) -------------
STUDY_BUDDY_SYSTEM_PROMPT = """
You are "Study Buddy" - a friendly, patient, and encouraging AI assistant that
helps students with academic questions using simple, beginner-friendly explanations.
Maintain a positive tone and focus on educational topics.

Key Rules:
1. RESPONSE STYLE:
   - Always use clear, simple language (middle/high school level)
   - Keep core explanations to 2-3 sentences
   - Explain technical terms in parentheses immediately
   - Use analogies/examples from everyday life
   - Structure responses:
     1. Quick answer
     2. Simple explanation
     3. Example/analogy (optional)
     4. Encouraging follow-up question

2. TONE:
   - Start with positive reinforcement ("Great question!", "I love your curiosity!")
   - Be supportive when students struggle ("No worries, let's break it down!")
   - Never make the student feel bad for not knowing

3. SAFETY & SCOPE:
   - Only answer school-related questions
   - For off-topic/inappropriate queries, respond:
     "I'm here to help with school topics! Try asking about science, math, history, or anything you're learning. 😊"
   - Never scold - always redirect kindly

"""

# Evaluator prompt / rubric (kept close to the PDF spec: outputs JSON-like structure)
EVALUATOR_SYSTEM_PROMPT = """
You are an automated evaluation system designed to assess the quality of outputs generated by another
AI model (the Target Model). Your task is to analyze the Target Model’s response based on a predefined
rubric and provide both quantitative scores and qualitative feedback.

Inputs Provided to You:
- Original Prompt (User Query): the initial instruction given to the Target Model.
- Target Model’s Output: the response generated by the AI system being evaluated.
- Evaluation Rubric: the structured criteria for assessment.

Evaluation Rubric & Scoring Guidelines
Evaluate the Target Model’s output on the following dimensions (scale: 0.0–5.0, where 5 = excellent):

1. Accuracy (Factual Correctness) - Does the response contain verifiable facts, free from errors or hallucinations?
2. Clarity & Coherence - Is the response well-structured, logically flowing, and easy to understand?
3. Tone & Professionalism - Does the output adhere to the required tone?
4. Relevance - Does the response stay strictly on-topic?
5. Conciseness - Is the response concise while preserving key information?

Response Format (STRICT JSON):
{
  "scores": {
    "accuracy": X.X,
    "coherence": X.X,
    "relevance": X.X,
    "tone": X.X,
    "clarity": X.X,
    "conciseness": X.X
  },
  "feedback": {
    "accuracy": "short comment on factual quality",
    "coherence": "short comment on logical flow",
    "relevance": "short comment on how well it answers the prompt",
    "tone": "short comment on tone appropriateness",
    "clarity": "short comment on understandability",
    "conciseness": "short comment on brevity and focus"
  },
  "overall_summary": "2-3 sentence summary of overall strengths & weaknesses"
}

IMPORTANT:
- Return STRICTLY one valid JSON object matching the schema above. Do NOT include extra explanation outside the JSON.
- Scores must be floats (one decimal place allowed, e.g., 4.0).
- Be concise in feedback (1-2 short sentences per field).
"""

# ------------- Helpers -------------
def safe_parse_json(text: str):
    """
    Try to extract first JSON object-looking substring and parse it.
    Returns dict or raises ValueError.
    """
    # Find first {...} block using simple bracket matching
    stack = []
    start = None
    for i, ch in enumerate(text):
        if ch == '{':
            if start is None:
                start = i
            stack.append('{')
        elif ch == '}':
            if stack:
                stack.pop()
                if not stack and start is not None:
                    candidate = text[start:i+1]
                    try:
                        return json.loads(candidate)
                    except Exception:
                        # try to fix trailing commas or single quotes
                        fixed = candidate.replace("'", "\"")
                        fixed = re.sub(r",\s*}", "}", fixed)
                        fixed = re.sub(r",\s*]", "]", fixed)
                        try:
                            return json.loads(fixed)
                        except Exception:
                            pass
                    # if parse fails, continue searching for next {...}
                    start = None
    raise ValueError("No valid JSON object found in model output.")


# ------------- Core pipeline -------------
def run_study_buddy_and_evaluate(user_query: str, verbose: bool = True):
    # Initialize target model (Study Buddy)
    # study_model = genai.GenerativeModel(
    #     model_name="gemini-2.5-flash",
    #     system_instruction=STUDY_BUDDY_SYSTEM_PROMPT
    # )
    # study_chat = study_model.start_chat()

    study_chat = client.chats.create(
        model="gemini-3.6-flash",
        config=types.GenerateContentConfig(
            system_instruction=STUDY_BUDDY_SYSTEM_PROMPT
        )
    )

    # Get target model's response
    if verbose:
        print("=== Sending user query to Study Buddy (target model) ===")
    study_resp = study_chat.send_message(user_query)
    target_output = study_resp.text if hasattr(study_resp, "text") else str(study_resp)

    if verbose:
        print("\n--- Target Model Output ---")
        print(target_output)
        print("---------------------------\n")

    # Build evaluator chat (separate LLM instance)
    # evaluator_model = genai.GenerativeModel(
    #     model_name="gemini-2.5-flash",
    #     system_instruction=EVALUATOR_SYSTEM_PROMPT
    # )
    # evaluator_chat = evaluator_model.start_chat()

    evaluator_chat = client.chats.create(
        model="gemini-3.6-flash",
        config=types.GenerateContentConfig(
            system_instruction=EVALUATOR_SYSTEM_PROMPT
        )
    )

    # Compose evaluation prompt content as a single message (inputs provided)
    eval_input = (
        f"Original Prompt (User Query):\n{user_query}\n\n"
        f"Target Model's Output:\n{target_output}\n\n"
        f"Please evaluate using the rubric and return ONLY the JSON specified."
    )

    if verbose:
        print("=== Sending content to Evaluator Model ===")

    eval_resp = evaluator_chat.send_message(eval_input)
    eval_text = eval_resp.text if hasattr(eval_resp, "text") else str(eval_resp)

    if verbose:
        print("\n--- Evaluator Raw Output ---")
        print(eval_text)
        print("---------------------------\n")

    # Parse evaluator JSON
    try:
        eval_json = safe_parse_json(eval_text)
    except ValueError as e:
        # If parsing fails, return raw text and error
        raise ValueError(f"Failed to parse evaluator JSON: {e}\n\nRaw evaluator output:\n{eval_text}")

    # Basic validation of expected keys
    for k in ("scores", "feedback", "overall_summary"):
        if k not in eval_json:
            raise ValueError(f"Evaluator JSON missing required key: {k}")

    return {
        "user_query": user_query,
        "target_output": target_output,
        "evaluator_result": eval_json
    }


# ------------- CLI -------------
def main():
    print("Evaluator pipeline (Study Buddy -> Evaluator). Type 'exit' to quit.")
    while True:
        q = input("\nUser query: ").strip()
        if not q:
            print("Please type a question, or 'exit' to quit.")
            continue
        if q.lower() in ("exit", "quit"):
            print("Goodbye.")
            break

        try:
            result = run_study_buddy_and_evaluate(q)
        except Exception as e:
            print(f"[Error] {e}")
            continue

        # Pretty print results
        print("\n=== EVALUATION SUMMARY ===")
        print("Original query:", result["user_query"])
        print("\nTarget model answer:\n", result["target_output"])
        print("\nEvaluator scores:")
        print(json.dumps(result["evaluator_result"].get("scores", {}), indent=2))
        print("\nEvaluator feedback:")
        print(json.dumps(result["evaluator_result"].get("feedback", {}), indent=2))
        print("\nOverall summary:")
        print(result["evaluator_result"].get("overall_summary"))
        print("===========================")


if __name__ == "__main__":
    main()
